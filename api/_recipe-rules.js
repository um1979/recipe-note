// 3) 혹시 제미나이가 규칙을 어겨도 타이머가 읽을 수 있게 고쳐 줘요
function normalizeStep(s) {
  s = String(s == null ? "" : s);
  // 1시간 30분 / 1시간 -> 분
  s = s.replace(/(\d+)\s*시간\s*(\d+)\s*분/g, function (_, h, m) { return (parseInt(h, 10) * 60 + parseInt(m, 10)) + "분"; });
  s = s.replace(/(\d+)\s*시간/g, function (_, h) { return (parseInt(h, 10) * 60) + "분"; });
  // 5~10분 -> 10분 (덜 익히지 않도록 큰 쪽)
  s = s.replace(/(\d+)\s*[~\-–]\s*(\d+)\s*(분|초)/g, function (_, a, b, u) { return b + u; });
  return s;
}
function normalizeSteps(arr) { return (Array.isArray(arr) ? arr : []).map(normalizeStep); }

